package org.docx4j.convert.out.fo;

import java.awt.Dimension;
import java.awt.geom.Dimension2D;
import java.awt.geom.Rectangle2D;

import org.apache.batik.dom.GenericDOMImplementation;
import org.apache.batik.svggen.SVGGeneratorContext;
import org.apache.batik.svggen.SVGGraphics2D;
import org.docx4j.model.images.MetafileRenderer;
import org.docx4j.model.images.MetafileSvgProvider;
import org.docx4j.model.images.PoiMetafileRenderer;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.w3c.dom.DOMImplementation;
import org.w3c.dom.Document;
import org.w3c.dom.Element;

/**
 * Renders a Windows metafile to SVG with Batik's {@code SVGGraphics2D}, for
 * {@code fo:instream-foreign-object} in XSL-FO and for an inline {@code <svg>} in
 * HTML.
 *
 * <p>Found through {@link java.util.ServiceLoader}: docx4j-core declares the
 * {@link MetafileSvgProvider} interface and this module supplies the
 * implementation, because {@code batik-svggen} is a dependency of
 * {@code docx4j-export-fo} and not of {@code docx4j-core}.  Nothing has to be
 * configured; adding this module to the classpath is enough.</p>
 *
 * <h3>Text: {@code <text>}, not outlines</h3>
 * The generated SVG keeps a metafile's text as {@code <text>} elements, so it is
 * still text in the PDF - searchable, selectable, copyable - wherever FOP can
 * resolve the font, and drawn as outlines by Batik where it cannot.  A metafile
 * names its fonts by GDI face name, and those are mapped through
 * {@link org.docx4j.fonts.PhysicalFonts} (the docx4j
 * {@code Docx4jDrawFontManager}, installed by {@link PoiMetafileRenderer}), which
 * is the same family-name mapping docx4j declares to FOP - so a face the document
 * elsewhere uses resolves to the same font here.  Set
 * {@value #TEXT_AS_SHAPES_PROPERTY} to true to emit outlines instead: that gives a
 * rendering identical to AWT's whatever fonts are installed, at the cost of
 * searchable text and a larger file.
 *
 * @since 17.1.0 (CR-011 phase 2)
 */
public class BatikMetafileSvgProvider implements MetafileSvgProvider {

	private static Logger log = LoggerFactory.getLogger(BatikMetafileSvgProvider.class);

	private static final String SVG_NS = "http://www.w3.org/2000/svg";

	/** Emit a metafile's text as glyph outlines rather than SVG {@code <text>}. */
	public static final String TEXT_AS_SHAPES_PROPERTY =
			"docx4j.convert.out.metafile.textAsShapes";

	public BatikMetafileSvgProvider() {}

	@Override
	public Document toSvgDocument(byte[] data, double widthPt, double heightPt) {

		MetafileRenderer renderer = PoiMetafileRenderer.getInstance();

		double w = widthPt;
		double h = heightPt;
		if (!(w > 0) || !(h > 0)) {
			// no frame declared (MetafilePart.toSVG(), or a picture with no extent):
			// the metafile's own size
			Dimension2D own = renderer.getSizeInPoints(data);
			if (own == null) return null;
			if (!(w > 0)) w = own.getWidth();
			if (!(h > 0)) h = own.getHeight();
		}
		if (!(w > 0) || !(h > 0)) return null;

		try {
			DOMImplementation impl = GenericDOMImplementation.getDOMImplementation();
			Document doc = impl.createDocument(SVG_NS, "svg", null);

			SVGGeneratorContext ctx = SVGGeneratorContext.createDefault(doc);
			ctx.setComment(null); // no "Generated by the Batik Graphics2D SVG Generator"
			ctx.setPrecision(4);

			boolean textAsShapes = org.docx4j.Docx4jProperties.getProperty(
					TEXT_AS_SHAPES_PROPERTY, false);
			SVGGraphics2D g = new SVGGraphics2D(ctx, textAsShapes);
			g.setSVGCanvasSize(new Dimension(
					(int)Math.max(1, Math.ceil(w)), (int)Math.max(1, Math.ceil(h))));

			renderer.draw(data, g, new Rectangle2D.Double(0, 0, w, h));

			Element root = doc.getDocumentElement();
			g.getRoot(root);

			/* The picture fills the frame the document gives it, exactly: the width and
			 * height are in points and the viewBox maps one user unit to one point, so
			 * FOP's content-width/content-height on the fo:instream-foreign-object (and
			 * a browser's layout of the inline <svg>) need no scaling at all. */
			root.setAttributeNS(null, "width", length(w) + "pt");
			root.setAttributeNS(null, "height", length(h) + "pt");
			root.setAttributeNS(null, "viewBox", "0 0 " + length(w) + " " + length(h));
			root.setAttributeNS(null, "preserveAspectRatio", "none");

			declareXlinkWhereUsed(root);

			return doc;

		} catch (Throwable t) {
			// the metafile parsers use bare asserts; see PoiMetafileRenderer
			log.warn("Could not render the metafile as SVG: " + t, t);
			return null;
		}
	}

	private static final String XMLNS_NS = "http://www.w3.org/2000/xmlns/";
	private static final String XLINK_NS = "http://www.w3.org/1999/xlink";

	/**
	 * Declares {@code xmlns:xlink} on every element that uses the prefix, not only on
	 * the {@code <svg>} root Batik puts it on.
	 *
	 * <p>Batik references an embedded bitmap as {@code <image xlink:href="data:...">},
	 * and it has to stay {@code xlink:href}: Batik's own {@code SVGImageElementBridge}
	 * - which is what FOP hands the SVG to - reads only the XLink attribute, and
	 * rewriting it to SVG 2's plain {@code href} made it throw a {@code BridgeException}
	 * and abandon the whole picture (measured).  So the prefix has to be bound, and
	 * Xalan drops namespace declarations from the SVG when the XSLT pathway copies it
	 * into the FO - the root's and the element's own alike.  The prefix is therefore
	 * bound on {@code fo:root} as well (docx2fo.xslt and FOExporterVisitorDelegate),
	 * and on the HTML root; this declaration is what makes the SVG self-contained
	 * anywhere else it is used, eg {@code MetafilePart.toSVG()}.</p>
	 */
	private static void declareXlinkWhereUsed(Element el) {
		org.w3c.dom.NamedNodeMap attrs = el.getAttributes();
		boolean uses = false;
		for (int i = 0; i < attrs.getLength(); i++) {
			org.w3c.dom.Node a = attrs.item(i);
			if (XLINK_NS.equals(a.getNamespaceURI())
					|| (a.getNodeName() != null && a.getNodeName().startsWith("xlink:"))) {
				uses = true;
				break;
			}
		}
		if (uses) {
			el.setAttributeNS(XMLNS_NS, "xmlns:xlink", XLINK_NS);
		}
		for (org.w3c.dom.Node n = el.getFirstChild(); n != null; n = n.getNextSibling()) {
			if (n instanceof Element) declareXlinkWhereUsed((Element)n);
		}
	}

	/** at most four decimals, no trailing zeros */
	private static String length(double v) {
		String s = String.format(java.util.Locale.ROOT, "%.4f", v);
		while (s.contains(".") && (s.endsWith("0") || s.endsWith("."))) {
			s = s.substring(0, s.length() - 1);
		}
		return s;
	}
}
