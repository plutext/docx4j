/**
 * docx4j's copy of FOP 2.11's LineLayoutManager with Word's greedy line breaking
 * (CR-001 Phase 5); see the package documentation.  Apart from
 * findOptimalBreakingPoints and the greedy members of LineBreakingAlgorithm,
 * the code is FOP's (Apache License 2.0), mechanically adapted: it extends
 * LineLayoutManager so the rest of FOP treats it as one, keeps its own state,
 * and reaches LineBreakPosition's package-private constructor and private
 * fields through LBP.
 *
 * Original: LayoutManager for lines. It builds one or more lines containing
 * inline areas generated by its sub layout managers.
 * A break is found for each line which may contain one of more
 * breaks from the child layout managers.
 * Once a break is found then it is return for the parent layout
 * manager to handle.
 * When the areas are being added to the page this manager
 * creates a line area to contain the inline areas added by the
 * child layout managers.
 */
